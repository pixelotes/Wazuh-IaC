#!/usr/bin/env bash
# Creates the Secrets in the cluster with random values (never written to Git).
# Only bcrypt hashes go to values/wazuh-credentials.yaml. Idempotent per group.
set -euo pipefail

CTX=${CTX:-kind-wazuh}
ROOT=$(cd "$(dirname "$0")/.." && pwd)
K="kubectl --context $CTX"

rand() { openssl rand -base64 96 | tr -dc 'A-Za-z0-9' | cut -c "1-${1:-24}"; }
# Wazuh API passwords need upper, lower, digit and symbol.
api_pass() { echo "Aa1!$(rand 20)"; }
bcrypt() { htpasswd -bnBC 12 "" "$1" | tr -d ':\n' | sed 's/^\$2y/$2a/'; }
ensure_ns() { $K create namespace "$1" --dry-run=client -o yaml | $K apply -f - >/dev/null; }

if $K -n wazuh get secret wazuh-indexer-cred >/dev/null 2>&1; then
  echo "wazuh secrets exist; skipping."
else
  ensure_ns wazuh
  INDEXER_PASSWORD=$(rand)
  DASHBOARD_PASSWORD=$(rand)

  # INDEXER_USERNAME is read by Filebeat in the manager (envFrom); without it the indexer answers 401
  $K -n wazuh create secret generic wazuh-indexer-cred \
    --from-literal=INDEXER_USERNAME=admin --from-literal=INDEXER_PASSWORD="$INDEXER_PASSWORD"
  $K -n wazuh create secret generic wazuh-dashboard-cred \
    --from-literal=DASHBOARD_USERNAME=kibanaserver --from-literal=DASHBOARD_PASSWORD="$DASHBOARD_PASSWORD"
  $K -n wazuh create secret generic wazuh-api-cred \
    --from-literal=API_USERNAME=wazuh-wui --from-literal=API_PASSWORD="$(api_pass)"
  $K -n wazuh create secret generic wazuh-authd-pass --from-literal=authd.pass="$(rand 24)"
  $K -n wazuh create secret generic wazuh-cluster-key --from-literal=key="$(rand 32)"

  cat >"$ROOT/values/wazuh-credentials.yaml" <<YAML
# Generated by scripts/gen-secrets.sh. bcrypt hashes only; the passwords are in cluster Secrets.
indexer:
  cred:
    passwordHash: "$(bcrypt "$INDEXER_PASSWORD")"
dashboard:
  cred:
    passwordHash: "$(bcrypt "$DASHBOARD_PASSWORD")"
YAML
  echo "Wrote values/wazuh-credentials.yaml (commit it)."
fi

# Local S3 (SeaweedFS): one identity shared by the store, the seed jobs and the Wazuh aws-s3 wodle.
if $K -n s3 get secret s3-cred >/dev/null 2>&1; then
  echo "s3 secrets exist; skipping."
else
  ensure_ns s3
  ensure_ns wazuh
  AK=$(rand 20 | tr 'a-z' 'A-Z')
  SK=$(rand 40)
  $K -n s3 create secret generic s3-cred \
    --from-literal=AWS_ACCESS_KEY_ID="$AK" --from-literal=AWS_SECRET_ACCESS_KEY="$SK"
  $K -n s3 create secret generic s3-config --from-literal=s3.json="$(cat <<JSON
{"identities":[{"name":"wazuh","credentials":[{"accessKey":"$AK","secretKey":"$SK"}],"actions":["Admin","Read","Write","List","Tagging"]}]}
JSON
)"
  # AWS shared credentials file read by the aws-s3 wodle (aws_profile=default)
  $K -n wazuh create secret generic wazuh-aws-credentials \
    --from-literal=credentials="$(printf '[default]\naws_access_key_id = %s\naws_secret_access_key = %s\n' "$AK" "$SK")"
fi

# S3 credentials for the indexer init container (builds the keystore used by the snapshot repository)
if $K -n wazuh get secret wazuh-s3-env >/dev/null 2>&1; then
  echo "wazuh-s3-env exists; skipping."
elif $K -n s3 get secret s3-cred >/dev/null 2>&1; then
  $K -n wazuh create secret generic wazuh-s3-env \
    --from-literal=AWS_ACCESS_KEY_ID="$($K -n s3 get secret s3-cred -o jsonpath='{.data.AWS_ACCESS_KEY_ID}' | base64 -d)" \
    --from-literal=AWS_SECRET_ACCESS_KEY="$($K -n s3 get secret s3-cred -o jsonpath='{.data.AWS_SECRET_ACCESS_KEY}' | base64 -d)"
fi

# Opsgenie / JSM Operations API key read by integrations/custom-opsgenie.py (the mock accepts any GenieKey)
if $K -n wazuh get secret wazuh-integrations-cred >/dev/null 2>&1; then
  echo "integration secrets exist; skipping."
else
  ensure_ns wazuh
  $K -n wazuh create secret generic wazuh-integrations-cred --from-literal=OPSGENIE_API_KEY="$(rand 36)"
fi

# SSO: Dex users and the OIDC client shared by Dex and the Wazuh dashboard
if $K -n dex get secret dex-cred >/dev/null 2>&1; then
  echo "dex secrets exist; skipping."
else
  ensure_ns dex
  ensure_ns wazuh
  ADMIN_PW=$(rand 16)
  ANALYST_PW=$(rand 16)
  CLIENT_SECRET=$(rand 32)
  dex_hash() { htpasswd -bnBC 10 "" "$1" | tr -d ':\n' | sed 's/^\$2y/$2a/'; }
  $K -n dex create secret generic dex-cred \
    --from-literal=ADMIN_PASSWORD_HASH="$(dex_hash "$ADMIN_PW")" \
    --from-literal=ANALYST_PASSWORD_HASH="$(dex_hash "$ANALYST_PW")" \
    --from-literal=WAZUH_OIDC_CLIENT_SECRET="$CLIENT_SECRET"
  # plain-text demo passwords, for whoever logs in (not mounted anywhere)
  $K -n dex create secret generic dex-demo-passwords \
    --from-literal=admin="$ADMIN_PW" --from-literal=analyst="$ANALYST_PW"
  $K -n wazuh create secret generic wazuh-oidc \
    --from-literal=OPENSEARCH_OIDC_CLIENT_ID=wazuh --from-literal=OPENSEARCH_OIDC_CLIENT_SECRET="$CLIENT_SECRET"
  echo "SSO users: admin@wazuh.local and analyst@wazuh.local. Password: $K -n dex get secret dex-demo-passwords -o jsonpath='{.data.admin}' | base64 -d"
fi

echo "Indexer admin password: $K -n wazuh get secret wazuh-indexer-cred -o jsonpath='{.data.INDEXER_PASSWORD}' | base64 -d"
